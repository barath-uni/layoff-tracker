#!/usr/bin/env bash
# Assemble the `site` branch tree in $1 (default: site-out): the built dist/, the Vercel functions + vercel.json,
# and a copy of the refresh workflow (scheduled workflows only run from the default branch, which is `site`).
set -euo pipefail
cd "$(dirname "$0")/.."
OUT="${1:-site-out}"
rm -rf "$OUT" && mkdir -p "$OUT/.github/workflows"
cp -a dist/. "$OUT/"
cp -a deploy/vercel/. "$OUT/"
cp .github/workflows/refresh.yml "$OUT/.github/workflows/"
printf '# Layoff Tracker: built site\n\nGenerated by the hourly workflow from the `main` branch. Do not edit here.\n' > "$OUT/README.md"
echo "assembled $(find "$OUT" -type f | wc -l) files in $OUT"
